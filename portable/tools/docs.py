"""Generated documentation: docs/PROBES.md and the README footprint section."""
from __future__ import annotations

import re

from spec import Spec

MARKER_PREFIX = "<!-- ENVSCAN:"
FOOTPRINT_MARKER = "<!-- ENVSCAN:FOOTPRINT -->"
VERSION_MARKER = "<!-- ENVSCAN:VERSION -->"
_MARKER_RE = re.compile(f"{re.escape(FOOTPRINT_MARKER)}|{re.escape(VERSION_MARKER)}")


def code_span(text: str) -> str:
    """`text` as a Markdown code span, so it renders literally: footprint lines hold placeholders
    such as "<jdk>" (an HTML tag to a renderer, which hides it), wildcards and underscores."""
    runs = {len(run) for run in re.findall(r"`+", text)}
    size = 1
    while size in runs:  # the fence must differ from every backtick run inside
        size += 1
    fence = "`" * size
    # A renderer strips one space from each end when both ends have one, and a backtick next to the
    # fence would join it, so pad in those cases.
    edge_space = text.startswith(" ") and text.endswith(" ") and text.strip() != ""
    if text.startswith("`") or text.endswith("`") or edge_space:
        text = f" {text} "
    return f"{fence}{text}{fence}"


def _impl_marks(spec: Spec, probe_id: str) -> list[str]:
    return ["yes" if probe_id in spec.footprints.get(impl.id, {}) else "-" for impl in spec.impls]


def probe_table(spec: Spec) -> str:
    columns = [impl.column for impl in spec.impls]
    rows = [
        "| " + " | ".join(["Probe", "Title", "Tier", "Scope", *columns]) + " |",
        "|" + "---|" * (4 + len(columns)),
    ]
    for probe in spec.probes:
        marks = " | ".join(_impl_marks(spec, probe["id"]))
        rows.append(f"| `{probe['id']}` | {probe['title']} | {probe['tier']} | {probe['scope']} | {marks} |")
    return "\n".join(rows)


def footprint_section(spec: Spec, heading_level: int = 3) -> str:
    """Every probe, per implementation, with exactly what it reads or runs."""
    hashes = "#" * heading_level
    parts: list[str] = []
    for impl in spec.impls:
        parts.append(f"{hashes} {impl.label}\n")
        for probe in spec.probes_for(impl.id):
            parts.append(f"- **`{probe['id']}`** ({probe['tier']}) - {probe['title']}")
            parts.extend(f"  - {code_span(line)}" for line in probe["footprint"])
        parts.append("")
    return "\n".join(parts)


def probes_markdown(spec: Spec) -> str:
    return "\n".join([
        "# envscan probe catalog",
        "",
        f"Generated by `tools/build.py` from `spec/*.toml` (envscan {spec.version}). Do not edit.",
        "",
        "Tiers: `default` runs without flags and sends no network traffic; `deep` (`--deep`) adds",
        "commands that security tooling may flag; `net` (`--net`) adds reachability checks against",
        "proxies and mirrors found in local configuration.",
        "",
        probe_table(spec),
        "",
        "## What each probe reads or runs",
        "",
        "\n".join(f"- `{p['id']}`: {p['about']}" for p in spec.probes),
        "",
        "## Footprint by implementation",
        "",
        footprint_section(spec),
    ])


def _unknown_marker(text: str) -> tuple[int, str] | None:
    """(line, text) of the first "<!-- ENVSCAN:" that is not a known marker."""
    for match in re.finditer(re.escape(MARKER_PREFIX), text):
        if not _MARKER_RE.match(text, match.start()):
            end = text.find("-->", match.start())
            marker = text[match.start():end + 3] if end >= 0 else text[match.start():match.start() + 40]
            return text.count("\n", 0, match.start()) + 1, marker
    return None


def render_readme(template: str, spec: Spec) -> str:
    """Fill the README template. It must hold each marker exactly once, and no
    "<!-- ENVSCAN:" text may survive rendering (an unknown or misspelled marker)."""
    for marker in (FOOTPRINT_MARKER, VERSION_MARKER):
        count = template.count(marker)
        if count != 1:
            raise ValueError(f"README template must contain {marker} exactly once, found {count}")
    unknown = _unknown_marker(template)
    if unknown:
        raise ValueError(f"README template line {unknown[0]}: unknown marker {unknown[1]!r}")
    values = {FOOTPRINT_MARKER: footprint_section(spec), VERSION_MARKER: spec.version}
    rendered = _MARKER_RE.sub(lambda match: values[match.group(0)], template)
    leftover = rendered.find(MARKER_PREFIX)
    if leftover >= 0:  # only spec text can bring one in now
        line = rendered.count("\n", 0, leftover) + 1
        raise ValueError(f"README line {line}: spec text contains {MARKER_PREFIX!r}")
    return rendered
